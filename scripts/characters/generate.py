#!/usr/bin/env python3
"""Generate every character SVG under assets/characters/ (stdlib only).

    python3 scripts/characters/generate.py            # all characters
    python3 scripts/characters/generate.py turbo pip  # some

Output is deterministic and byte-stable. The SVGs are build inputs for
scripts/build_assets.sh; edit the character modules here, never the SVGs.

Per character (24 files):
  <n>_default|joy|scared|speed.svg         standing, no vehicle (selection UI)
  <n>_flying.svg, <n>_fly_<expr>.svg       riding its own vehicle (in-flight atlas)
  <n>_cloud_<expr>.svg                     riding the shared Cloud Surf cloud
  <n>_back_<expr>.svg, <n>_cloudback_<expr>.svg  the same two rides seen from behind
  <n>_icon.svg                             head portrait in a ring
  <n>_silhouette.svg                       one-colour shape
  <n>_vehicle_only.svg                     the vehicle by itself
Plus assets/characters/shared/cloud_vehicle_only.svg (the Cloud Surf cloud).
"""
import importlib
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import kit
from kit import *

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "assets", "characters")
NAMES = ["turbo", "pip", "nutty", "mochi", "bounce", "hoppy"]
EXPRS = ["default", "joy", "scared", "speed"]


def stand(m, expr):
    st = m.STAND
    return ground() + place(m.fig(expr), st["s"], 256, st["by"]) + (fx(expr, (70, 70, 442, 440)) if expr != "default" else "")


def cloud_ride(m, expr):
    c = m.CLOUD
    rot = {"speed": -6, "scared": 5}.get(expr, 0)
    inner = cloud(256, 404, 0.9, back=True) + place(m.fig(expr), c["s"], 256, c["by"]) + cloud(256, 404, 0.9)
    return group(inner, rot=rot) + fx(expr, (40, 40, 472, 440))


def cloud_ride_back(m, expr):
    c = m.CLOUD
    rot = {"speed": 6, "scared": -5}.get(expr, 0)
    inner = cloud(256, 404, 0.9, back=True) + place(m.fig_back(expr), c["s"], 256, c["by"]) + cloud(256, 404, 0.9)
    return group(inner, rot=rot) + fx(expr, (40, 40, 472, 440))


def icon(m):
    ic = m.ICON
    p = m.PAL
    ring = C(256, 256, 236)
    s = ic["s"]
    inner = '<g transform="translate(%s %s) scale(%s)">\n%s</g>\n' % (
        f(ic["cx"] - 256 * s), f(ic["cy"] - 200 * s), f2(s), m.head("default"))
    return (flat(ring, p["light"]) + clipped(C(256, 256, 228), inner)
            + stroke(ring, p["main"], 14))


def silhouette(m):
    body = place(m.fig("default"), m.STAND["s"], 256, m.STAND["by"])
    body = re.sub(r'#[0-9A-Fa-f]{6}', m.PAL["line"], body)
    body = re.sub(r' opacity="[0-9.]+"', "", body)
    return body


def app_icon():
    """1024 App Store icon: Turbo on the Shell Jet over a sky gradient.
    Full-bleed square (iOS masks the corners itself)."""
    import turbo
    kit.reset()
    sky = ('<defs><linearGradient id="sky" x1="0" y1="0" x2="0" y2="1">'
           '<stop offset="0" stop-color="#4FA3F0"/><stop offset="0.6" stop-color="#8CC8F8"/>'
           '<stop offset="1" stop-color="#D8F0FF"/></linearGradient></defs>\n'
           '<rect x="0" y="0" width="1024" height="1024" fill="url(#sky)"/>\n')
    deco = ""
    for cx, cy, s in ((150, 800, 1.0), (880, 720, 0.8), (860, 200, 0.55), (130, 250, 0.45)):
        for dx, dy, r in ((-90, 10, 60), (-20, -20, 80), (60, 0, 70), (120, 20, 46)):
            deco += flat(C(cx + dx * s, cy + dy * s, r * s), "#FFFFFF", op=0.85)
    deco += sparkle(150, 480, 30, "#FFE27A") + sparkle(890, 430, 24, "#FFE27A") + sparkle(770, 110, 16, "#FFFFFF")
    hero = '<g transform="translate(-13 -30) scale(2.05)">\n%s</g>\n' % turbo.ride("default")
    return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" fill="none">\n'
            "<!-- app icon - generated by scripts/characters/generate.py; edit the generator, not this file -->\n"
            + sky + deco + hero + "</svg>\n")


def main(argv):
    names = argv or NAMES
    for name in names:
        d = os.path.join(OUT, name)
        os.makedirs(d, exist_ok=True)
        m = importlib.import_module(name)
        # each file gets its own id counter so output is independent of order
        for key, fn in file_plan(name, m):
            kit.reset()
            with open(os.path.join(d, key + ".svg"), "w") as fh:
                fh.write(svg(fn(), key))
        print("  ✓ %s (%d files)" % (name, len(file_plan(name, m))))
    if not argv:
        kit.reset()
        d = os.path.join(OUT, "shared")
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, "cloud_vehicle_only.svg"), "w") as fh:
            fh.write(svg(cloud(254, 258, 1.12, back=True) + cloud(254, 258, 1.12), "cloud_vehicle_only"))
        print("  ✓ shared/cloud_vehicle_only.svg")
    if not argv or "turbo" in names:
        with open(os.path.join(ROOT, "assets", "ui", "app-icon", "app_icon.svg"), "w") as fh:
            fh.write(app_icon())
        print("  ✓ app_icon.svg")


def file_plan(name, m):
    plan = []
    for e in EXPRS:
        plan.append(("%s_%s" % (name, e), lambda e=e: stand(m, e)))
        plan.append(("%s_fly_%s" % (name, e), lambda e=e: m.ride(e)))
        plan.append(("%s_cloud_%s" % (name, e), lambda e=e: cloud_ride(m, e)))
        # back views: flying away from the chase camera (the in-flight default)
        plan.append(("%s_back_%s" % (name, e), lambda e=e: m.ride_back(e)))
        plan.append(("%s_cloudback_%s" % (name, e), lambda e=e: cloud_ride_back(m, e)))
    plan.append(("%s_flying" % name, lambda: m.ride("default")))
    plan.append(("%s_icon" % name, lambda: icon(m)))
    plan.append(("%s_silhouette" % name, lambda: silhouette(m)))
    plan.append(("%s_vehicle_only" % name, lambda: m.vehicle()))
    return plan


if __name__ == "__main__":
    main(sys.argv[1:])
